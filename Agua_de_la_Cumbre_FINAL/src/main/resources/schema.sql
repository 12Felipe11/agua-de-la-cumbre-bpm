CREATE TABLE IF NOT EXISTS ac_equipo (
 id VARCHAR(80) PRIMARY KEY, tipo VARCHAR(40) NOT NULL, estado VARCHAR(30) NOT NULL,
 responsable VARCHAR(100), version BIGINT DEFAULT 0 NOT NULL
);
CREATE TABLE IF NOT EXISTS ac_lote (
 id VARCHAR(80) PRIMARY KEY, presentacion VARCHAR(40) NOT NULL, fabricacion DATE NOT NULL,
 vencimiento DATE NOT NULL, disponible BIGINT NOT NULL CHECK(disponible >= 0),
 reservado BIGINT DEFAULT 0 NOT NULL CHECK(reservado >= 0),
 liberado BOOLEAN DEFAULT TRUE NOT NULL
);
CREATE TABLE IF NOT EXISTS ac_pedido (
 id VARCHAR(80) PRIMARY KEY, cliente VARCHAR(100) NOT NULL, vendedor VARCHAR(100) NOT NULL,
 zona VARCHAR(100) NOT NULL, lote VARCHAR(80) NOT NULL, cantidad BIGINT NOT NULL,
 total BIGINT NOT NULL, estado VARCHAR(40) NOT NULL, comprobante VARCHAR(200), canal VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS ac_cuenta (
 id VARCHAR(80) PRIMARY KEY, tipo VARCHAR(20) NOT NULL, tercero VARCHAR(100) NOT NULL,
 total BIGINT NOT NULL CHECK(total > 0), saldo BIGINT NOT NULL CHECK(saldo >= 0),
 estado VARCHAR(30) NOT NULL, gestion VARCHAR(80)
);
CREATE TABLE IF NOT EXISTS ac_movimiento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, instancia VARCHAR(80) NOT NULL,
 tipo VARCHAR(40) NOT NULL, referencia VARCHAR(100) NOT NULL, detalle VARCHAR(2000) NOT NULL,
 valor BIGINT NOT NULL DEFAULT 0, fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ac_plan (
 periodo VARCHAR(7) PRIMARY KEY, presupuesto BIGINT NOT NULL CHECK(presupuesto > 0)
);

CREATE TABLE IF NOT EXISTS ac_pago (
 documento VARCHAR(80) NOT NULL, comprobante VARCHAR(200) NOT NULL,
 valor BIGINT NOT NULL CHECK(valor>0), PRIMARY KEY(documento,comprobante)
);

